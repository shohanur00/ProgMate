/**
 * @file    swd_timer.c
 * @brief   TIM6-based timer service for SWD operations.
 *
 * @target  STM32G431CBT6
 */

#include "swd_timer.h"

#include "stm32g431xx.h"

/* --------------------------------------------------------------------------
 * Configuration
 * -------------------------------------------------------------------------- */

/*
 * Set this to the actual TIM6 input clock frequency from your
 * clock-tree configuration.
 *
 * Do not assume that the TIM6 clock is equal to the CPU clock.
 */


#define SWD_TIMER_INPUT_CLOCK_HZ    (170000000U)
#ifndef SWD_TIMER_INPUT_CLOCK_HZ
#error "Define SWD_TIMER_INPUT_CLOCK_HZ from the actual TIM6 clock configuration."
#endif

#define SWD_TIMER_MAX_ARR_VALUE    (0xFFFFU)

/* --------------------------------------------------------------------------
 * Private state
 * -------------------------------------------------------------------------- */

static volatile bool s_running = false;
static SWD_TimerCallback_t s_callback = (SWD_TimerCallback_t)0;

/* --------------------------------------------------------------------------
 * Public functions
 * -------------------------------------------------------------------------- */

bool SWD_Timer_Init(uint32_t tick_hz)
{
    uint32_t prescaler;
    uint32_t timer_clock;
    uint32_t period;

    if ((tick_hz == 0U) || (tick_hz > SWD_TIMER_INPUT_CLOCK_HZ))
    {
        return false;
    }

    if (s_running)
    {
        SWD_Timer_Stop();
    }

    /*
     * Enable TIM6 peripheral clock.
     * On STM32G431, TIM6 is connected to APB1.
     */
    RCC->APB1ENR1 |= RCC_APB1ENR1_TIM6EN;
    (void)RCC->APB1ENR1;

    /* Reset TIM6 configuration. */
    TIM6->CR1  = 0U;
    TIM6->DIER = 0U;
    TIM6->PSC  = 0U;
    TIM6->ARR  = 0U;
    TIM6->CNT  = 0U;
    TIM6->SR   = 0U;

    /*
     * Choose a prescaler so that the timer counter frequency
     * does not exceed the requested tick frequency.
     */
    prescaler = SWD_TIMER_INPUT_CLOCK_HZ / tick_hz;

    if (prescaler == 0U)
    {
        return false;
    }

    /*
     * PSC register stores divider - 1.
     * Use a prescaler that fits in the 16-bit PSC register.
     */
    if (prescaler > 65536U)
    {
        prescaler = 65536U;
    }

    timer_clock = SWD_TIMER_INPUT_CLOCK_HZ / prescaler;

    /*
     * ARR determines the update-event frequency:
     * update_hz = timer_clock / (ARR + 1).
     */
    period = timer_clock / tick_hz;

    if ((period == 0U) ||
        (period > (SWD_TIMER_MAX_ARR_VALUE + 1U)))
    {
        return false;
    }

    TIM6->PSC = prescaler - 1U;
    TIM6->ARR = period - 1U;
    TIM6->CNT = 0U;

    /* Load PSC and ARR into their active registers. */
    TIM6->EGR = TIM_EGR_UG;

    /* Clear update flag generated by the update event. */
    TIM6->SR = 0U;

    /* Enable update interrupt in TIM6. */
    TIM6->DIER |= TIM_DIER_UIE;

    /* Configure NVIC interrupt. */
    NVIC_ClearPendingIRQ(TIM6_DAC_IRQn);
    NVIC_EnableIRQ(TIM6_DAC_IRQn);

    s_running = false;

    return true;
}


bool SWD_Timer_Start(void)
{
    if ((TIM6->DIER & TIM_DIER_UIE) == 0U)
    {
        return false;
    }

    TIM6->CNT = 0U;
    TIM6->SR = 0U;

    NVIC_ClearPendingIRQ(TIM6_DAC_IRQn);

    s_running = true;
    TIM6->CR1 |= TIM_CR1_CEN;

    return true;
}


void SWD_Timer_Stop(void)
{
    TIM6->CR1 &= ~TIM_CR1_CEN;

    s_running = false;
}


bool SWD_Timer_IsRunning(void)
{
    return s_running;
}


void SWD_Timer_SetCallback(SWD_TimerCallback_t callback)
{
    s_callback = callback;
}


void SWD_Timer_IRQHandler(void)
{
    if ((TIM6->SR & TIM_SR_UIF) == 0U)
    {
        return;
    }

    /* Clear the update interrupt flag. */
    TIM6->SR = (uint32_t)~TIM_SR_UIF;

    if ((s_running == true) &&
        (s_callback != (SWD_TimerCallback_t)0))
    {
        s_callback();
    }
}


/* --------------------------------------------------------------------------
 * Interrupt handler
 * -------------------------------------------------------------------------- */

/**
 * @brief TIM6 global interrupt handler.
 *
 * If your project already defines this handler elsewhere, do not
 * define it again. Call SWD_Timer_IRQHandler() from the existing handler.
 */
void TIM6_DAC_IRQHandler(void)
{
    SWD_Timer_IRQHandler();
}